// Turns Natural Earth's coastline GeoJSON into Sources/SwitchboardRender/WorldOutline.swift.
//
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_coastline.geojson
//   swift scripts/make-coastline.swift ne_110m_coastline.geojson > Sources/SwitchboardRender/WorldOutline.swift
//
// The output is committed, so building Switchboard never downloads anything; run this only
// to change the scale (ne_50m_coastline is about twenty times denser) or take a newer release.
// Natural Earth is in the public domain.

import Foundation

guard CommandLine.arguments.count == 2,
      let data = FileManager.default.contents(atPath: CommandLine.arguments[1]),
      let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
      let features = root["features"] as? [[String: Any]] else {
    FileHandle.standardError.write("usage: swift make-coastline.swift ne_110m_coastline.geojson\n".data(using: .utf8)!)
    exit(1)
}

var lines: [[(lat: Double, lon: Double)]] = []
for feature in features {
    guard let geometry = feature["geometry"] as? [String: Any], let type = geometry["type"] as? String else { continue }
    let parts: [[[Double]]]
    switch type {
    case "LineString": parts = [geometry["coordinates"] as? [[Double]] ?? []]
    case "MultiLineString": parts = geometry["coordinates"] as? [[[Double]]] ?? []
    default: continue
    }
    for part in parts {
        // GeoJSON is (longitude, latitude). Two decimals is about a kilometre, far finer than this scale.
        var line: [(lat: Double, lon: Double)] = []
        for coordinate in part where coordinate.count >= 2 {
            let point = (lat: (coordinate[1] * 100).rounded() / 100, lon: (coordinate[0] * 100).rounded() / 100)
            if let last = line.last, last == point { continue }
            line.append(point)
        }
        if line.count >= 2 { lines.append(line) }
    }
}

func number(_ value: Double) -> String {
    var text = String(format: "%.2f", value)
    while text.hasSuffix("0") { text.removeLast() }
    if text.hasSuffix(".") { text.removeLast() }
    return text == "-0" ? "0" : text
}

let total = lines.reduce(0) { $0 + $1.count }
var out = """
// Generated by scripts/make-coastline.swift from Natural Earth's 1:110m coastline
// (naturalearthdata.com, public domain). Do not edit by hand; run the script again.
// \(lines.count) lines, \(total) points.

/// The world's coastlines as lines of (latitude, longitude) in degrees.
///
/// Natural Earth's 1:110m scale: made for a whole world on one screen, which is what the
/// globe is. Stored flat so the compiler reads one plain array rather than thousands of tuples.
enum WorldOutline {
    static let rings: [[(Float, Float)]] = {
        var rings: [[(Float, Float)]] = []
        rings.reserveCapacity(lengths.count)
        var index = 0
        for length in lengths {
            var ring: [(Float, Float)] = []
            ring.reserveCapacity(length)
            for _ in 0..<length {
                ring.append((points[index], points[index + 1]))
                index += 2
            }
            rings.append(ring)
        }
        return rings
    }()

    /// The number of points in each line.
    private static let lengths: [Int] = [

"""
out += lines.map { String($0.count) }.chunked(24).map { "        " + $0.joined(separator: ", ") + "," }.joined(separator: "\n")
out += "\n    ]\n\n    /// Latitude, longitude, latitude, longitude, ...\n    private static let points: [Float] = [\n"
let flat = lines.flatMap { $0.flatMap { [number($0.lat), number($0.lon)] } }
out += flat.chunked(16).map { "        " + $0.joined(separator: ", ") + "," }.joined(separator: "\n")
out += "\n    ]\n}\n"
print(out, terminator: "")

extension Array {
    func chunked(_ size: Int) -> [[Element]] {
        stride(from: 0, to: count, by: size).map { Array(self[$0..<Swift.min($0 + size, count)]) }
    }
}
